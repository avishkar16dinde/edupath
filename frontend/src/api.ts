// WHAT-IF SCENARIO
// ============================================================

export async function simulateScenario(
  profile: StudentProfile,
  scenario: string
) {
  const backendProfile =
    toBackendProfile(profile);


  if (!scenario.trim()) {
    throw new Error(
      "Please enter a what-if scenario."
    );
  }


  console.log(
    "Sending scenario to Groq:",
    scenario
  );


  let response: Response;

  try {
    response = await fetch(
      `${API_BASE}/api/scenarios`,
      {
        method: "POST",

        headers: {
          "Content-Type":
            "application/json",
        },

        body: JSON.stringify({
          profile:
            backendProfile,

          scenario:
            scenario.trim(),
        }),
      }
    );
  } catch (error) {
    console.error(
      "Scenario backend connection error:",
      error
    );

    throw new Error(
      "Cannot connect to the AI backend."
    );
  }


  let data: any;

  try {
    data = await response.json();
  } catch {
    throw new Error(
      `Backend returned an invalid scenario response (${response.status}).`
    );
  }


  if (!response.ok) {
    console.error(
      "Scenario API error:",
      data
    );

    throw new Error(
      data?.detail ??
      `Scenario simulation failed (${response.status}).`
    );
  }


  console.log(
    "Groq scenario response:",
    data
  );


  return data;
}


